const LanguageContext = createContext({
  language: 'ro',
  setLanguage: () => {},
  t: (key) => key
});

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    const explicit = localStorage.getItem('app_language_explicit');
    const saved = localStorage.getItem('app_language');
    if (explicit !== 'true') {
      localStorage.setItem('app_language', 'ro');
      return 'ro';
    }
    return saved || 'ro';
  });

  const setLanguage = (lang, isExplicit = true) => {
    if (translations[lang]) {
      setLanguageState(lang);
      localStorage.setItem('app_language', lang);
      if (isExplicit) {
        localStorage.setItem('app_language_explicit', 'true');
      }
      document.documentElement.lang = lang;
    }
  };

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const t = (key) => {
    const langDict = translations[language] || translations.ro || translations.en;
    return langDict[key] || translations.ro?.[key] || translations.en?.[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useTranslation() {
  return useContext(LanguageContext);
}

export default translations;
