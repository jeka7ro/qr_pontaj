const LOCALES = { ro: 'ro-RO', en: 'en-GB', fr: 'fr-FR', nl: 'nl-NL' };

export function getLogsLabels(language) {
  const lang = LABELS[language] ? language : 'ro';
  const L = LABELS[lang];
  return {
    L,
    locale: LOCALES[lang],
    // Traduce motivele salvate de server (in romana) in limba curenta; motivele introduse manual raman neschimbate
    translateReason: (reason) => {
      if (!reason) return reason;
      const map = {
        [LABELS.ro.reasonPinPunch]: L.reasonPinPunch,
        [LABELS.ro.reasonPinStatus]: L.reasonPinStatus,
        [LABELS.ro.reasonCodePunch]: L.reasonCodePunch,
        [LABELS.ro.reasonCodeStatus]: L.reasonCodeStatus,
        [LABELS.ro.reasonBothPunch]: L.reasonBothPunch,
        [LABELS.ro.reasonBothStatus]: L.reasonBothStatus,
        [LABELS.ro.reasonQrExpired]: L.reasonQrExpired,
        [LABELS.ro.reasonArchived]: L.reasonArchived
      };
      return map[reason] || reason;
    }
  };
}

